#!/usr/bin/env node
// dsh profile regen drill (#6888 item 3). `trantor connect` used to short-circuit the dsh branch
// on patch-file EXISTENCE, so a profile written by an older connect never gained the rows a newer
// connect writes (graft was the first victim). The gate is now content-based: every row id this
// connect would write must already be in the patch; a missing one regenerates (backed up).
// Everything runs in a temp HOME with stub `dsh`/`graft` binaries — no live config is touched.
import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, chmodSync, rmSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { drillEnv } from "../drill-env.mjs";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));

let pass = 0, fail = 0;
const ok = (name, condition, detail = "") => {
  console.log(`  ${condition ? "PASS" : "FAIL"}  ${name}${detail ? ` — ${detail}` : ""}`);
  condition ? pass++ : fail++;
};

const stub = (dir, name) => {
  const p = join(dir, name);
  writeFileSync(p, "#!/bin/sh\nexit 0\n");
  chmodSync(p, 0o755);
};

// A profile patch as an OLDER connect (pre-graft) would have left it: two rows, old header.
const OLD_PATCH = `# trantor — generated by \`trantor connect\` (edits survive: regenerate by deleting this file)
- insert:
    - id: trantor-cc-hooks
      name: '@deepseek-ai/dsh-hooks-claude-code'
      config:
        configPath: /home/.dsh/profiles/trantor/hooks.seat.json
        pluginRoot: /trantor
    - id: trantor-relay
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: relay
        transport: stdio
        command: node
        args: ['/trantor/mcp.mjs']
`;

const setup = ({ withGraft, profile }) => {
  const work = mkdtempSync(join(tmpdir(), "trantor-connect-dsh-"));
  const home = join(work, "home");
  const fakebin = join(work, "bin");
  mkdirSync(fakebin, { recursive: true });
  stub(fakebin, "dsh");
  if (withGraft) stub(fakebin, "graft");
  const prof = join(home, ".dsh", "profiles", "trantor");
  if (profile) {
    mkdirSync(prof, { recursive: true });
    writeFileSync(join(prof, "cordis.patch.yml"), profile);
  }
  const run = (args = []) => spawnSync(process.execPath, [join(ROOT, "bin", "connect.mjs"), ...args], {
    cwd: ROOT,
    env: { ...drillEnv(), HOME: home, PATH: `${fakebin}:/usr/bin:/bin` },
    encoding: "utf8",
  });
  return { work, home, prof, run, patchPath: join(prof, "cordis.patch.yml") };
};

console.log("# trantor connect — dsh profile regen");

// 1. the bug: pre-existing profile, graft now installed → the missing row must be added, not skipped.
{
  const t = setup({ withGraft: true, profile: OLD_PATCH });
  const r = t.run();
  const after = existsSync(t.patchPath) ? readFileSync(t.patchPath, "utf8") : "";
  ok("a deficient profile is regenerated, not skipped", r.status === 0 && /dsh\s+regenerated/.test(r.stdout), r.stderr || r.stdout);
  ok("the regen adds the row connect now writes (graft)", after.includes("- id: trantor-graft") && after.includes("serverName: graft"), after.split("\n").slice(0, 3).join(" | "));
  ok("the regen keeps the rows that were already there", after.includes("- id: trantor-relay") && after.includes("- id: trantor-cc-hooks"));
  ok("the regen is backed up before the rewrite", readdirSync(t.prof).some(f => f.startsWith("cordis.patch.yml.bak-")), readdirSync(t.prof).join(", "));
  rmSync(t.work, { recursive: true, force: true });
}

// 2. a current profile (every row present) is still "already wired", byte-untouched.
{
  const t = setup({ withGraft: true, profile: null });
  t.run(); // fresh path writes the current patch (install may fail offline — files are what matter)
  const before = readFileSync(t.patchPath, "utf8");
  const r = t.run();
  ok("a profile that already has every row reports already wired", r.status === 0 && /dsh\s+already wired/.test(r.stdout), r.stderr || r.stdout);
  ok("already wired leaves the patch byte-identical", readFileSync(t.patchPath, "utf8") === before);
  rmSync(t.work, { recursive: true, force: true });
}

// 3. graft NOT installed: an old two-row profile is complete (connect writes no graft row), so no regen.
{
  const t = setup({ withGraft: false, profile: OLD_PATCH });
  const r = t.run();
  ok("without graft installed, a pre-graft profile is already current", r.status === 0 && /dsh\s+already wired/.test(r.stdout), r.stderr || r.stdout);
  ok("no graft row appears when graft is not installed", !readFileSync(t.patchPath, "utf8").includes("trantor-graft"));
  rmSync(t.work, { recursive: true, force: true });
}

// 4. dry-run reports the regen but touches nothing.
{
  const t = setup({ withGraft: true, profile: OLD_PATCH });
  const r = t.run(["--dry-run"]);
  ok("dry-run reports the regen it would do", r.status === 0 && /dsh\s+regenerated/.test(r.stdout), r.stderr || r.stdout);
  ok("dry-run leaves the deficient patch untouched", readFileSync(t.patchPath, "utf8") === OLD_PATCH);
  rmSync(t.work, { recursive: true, force: true });
}

// 5. no profile at all → the fresh path still creates the full profile.
{
  const t = setup({ withGraft: true, profile: null });
  const r = t.run();
  const patch = existsSync(t.patchPath) ? readFileSync(t.patchPath, "utf8") : "";
  ok("a fresh machine creates the profile with every row", r.status === 0 && patch.includes("- id: trantor-relay") && patch.includes("- id: trantor-graft"), r.stderr || r.stdout);
  rmSync(t.work, { recursive: true, force: true });
}

console.log(`# connect-dsh-regen: ${pass} pass, ${fail} fail`);
process.exit(fail ? 1 : 0);
